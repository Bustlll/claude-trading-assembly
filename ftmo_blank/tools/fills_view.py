"""FILLS VIEW: the live trade mechanism, readable by the operator.

Reads state/ledger.jsonl and writes:
  state/fills.csv    every order, fill, stop move, close and refusal, one row each
  state/entries.csv  one row per order: decision time/price/SL/TP/why, fill time/price/slippage,
                      exit time/price/result/R -- for checking whether a fill looks like something the
                      market could really have given, not an invented or impossible price
  state/fills.html   the same as a page, with an equity curve, the entries table and the event timeline

Regenerated by driver.py at the end of every turn. Open the html in a browser, or run
  python3 tools/fills_view.py
"""
import csv
import html
import json
import sys
from pathlib import Path

HOME = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(HOME))
from guard import rules as R  # noqa: E402

FILL_TYPES = {"order_placed", "trade_opened", "trade_closed", "order_rejected", "stop_moved", "close_placed",
              "rule_breach", "risk_warning", "goal_passed", "field_read", "note", "day_closed", "replay_end"}


def read_ledger(path: Path) -> list[dict]:
    if not path.exists():
        return []
    with open(path) as f:
        return [json.loads(line) for line in f if line.strip()]


def describe(r: dict) -> str:
    t = r["type"]
    if t == "order_placed":
        return f"order #{r['id']} {r['side']} {r['lots']} lots, sl {r['sl']}, tp {r['tp']} — {r['why']}"
    if t == "trade_opened":
        return f"FILL #{r['id']} {r['side']} {r['lots']} lots at {r['entry']} (risk ${r['risk_usd']})"
    if t == "trade_closed":
        return (f"CLOSE #{r['id']} {r['side']} {r['lots']} lots at {r['exit']} by {r['reason']}: "
                f"net ${r['net_usd']}, R {r['r_multiple']} ({r['result']})")
    if t == "order_rejected":
        return f"REFUSED at fill #{r['id']}: {r['reason']}"
    if t == "stop_moved":
        return f"stop #{r['id']} {r['old_sl']} -> {r['new_sl']} — {r['why']}"
    if t == "close_placed":
        return f"close requested #{r['id']} — {r['why']}"
    if t == "note":
        return f"journal ({r.get('day')}): {r['text'][:140]}"
    if t == "day_closed":
        return f"day {r['day']} closed: pnl ${r['day_pnl']} traded={r['traded']}"
    if t in ("rule_breach", "risk_warning"):
        return f"{t}: {json.dumps({k: v for k, v in r.items() if k not in ('type', 'bar', 'utc')})}"
    return t + (f" {r.get('goal', '')}" if r.get("goal") else "")


def equity_points(rows: list[dict]) -> list[tuple[str, float]]:
    pts = [("start", R.START_BALANCE)]
    for r in rows:
        if r["type"] == "trade_closed":
            pts.append((r["closed_utc"], r["balance"]))
    return pts


def svg_curve(points: list[tuple[str, float]]) -> str:
    w, h, pad = 760, 220, 36
    vals = [v for _, v in points]
    lo, hi = min(vals + [R.START_BALANCE]) - 5, max(vals + [R.START_BALANCE]) + 5
    span = max(hi - lo, 1e-9)
    n = max(len(points) - 1, 1)
    xy = [(pad + i * (w - 2 * pad) / n, h - pad - (v - lo) / span * (h - 2 * pad)) for i, (_, v) in enumerate(points)]
    line = " ".join(f"{x:.1f},{y:.1f}" for x, y in xy)
    base_y = h - pad - (R.START_BALANCE - lo) / span * (h - 2 * pad)
    dots = "".join(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="3" fill="#2a7"/>' for x, y in xy)
    return (f'<svg viewBox="0 0 {w} {h}" width="100%" role="img" aria-label="equity curve">'
            f'<line x1="{pad}" y1="{base_y:.1f}" x2="{w - pad}" y2="{base_y:.1f}" stroke="#999" stroke-dasharray="4 4"/>'
            f'<text x="{pad}" y="{pad - 10}" font-size="11" fill="#666">balance after each close (start {R.START_BALANCE:.0f})</text>'
            f'<polyline points="{line}" fill="none" stroke="#2a7" stroke-width="2"/>{dots}</svg>')


def entries(rows: list[dict]) -> list[dict]:
    """One row per order: the decision (when it wanted in, at what price, SL/TP, why) next to what
    actually happened (fill time/price, slippage from the decision price, then the close). This is
    for replay checking: was the requested entry at a time/price the market could really fill, or does
    the slippage look wrong (a gap, a stale price, an impossible level)?"""
    placed = {r["id"]: r for r in rows if r["type"] == "order_placed"}
    opened = {r["id"]: r for r in rows if r["type"] == "trade_opened"}
    closed = {r["id"]: r for r in rows if r["type"] == "trade_closed"}
    rejected = {r["id"]: r for r in rows if r["type"] == "order_rejected"}
    out = []
    for oid, p in sorted(placed.items()):
        o = opened.get(oid)
        c = closed.get(oid)
        rj = rejected.get(oid)
        sym = p.get("symbol")
        half = (R.spec(sym)["spread_price_snapshot"] / 2) if sym in R.INSTRUMENTS else None
        slip = round(o["entry"] - p["ref"], 6) if (o and p.get("ref") is not None) else None
        out.append({
            "id": oid, "symbol": sym, "side": p.get("side"), "lots": p.get("lots"),
            "decision_utc": p.get("utc"), "ref_price": p.get("ref"), "sl": p.get("sl"), "tp": p.get("tp"),
            "why": p.get("why"),
            "fill_utc": (o.get("opened_utc") or o.get("utc")) if o else None, "fill_price": o.get("entry") if o else None,
            "slippage": slip, "expected_half_spread": round(half, 6) if half is not None else None,
            "slippage_vs_expected": (round(abs(slip) - half, 6) if slip is not None and half is not None else None),
            "rejected_reason": rj.get("reason") if rj else None,
            "exit_utc": c.get("closed_utc") if c else None, "exit_price": c.get("exit") if c else None,
            "exit_reason": c.get("reason") if c else None, "result": c.get("result") if c else
            ("rejected" if rj else ("open" if o else "pending")),
            "net_usd": c.get("net_usd") if c else None, "r_price": c.get("r_price") if c else None,
            "r_net": c.get("r_net") if c else None,
        })
    return out


def write_entries_csv(path: Path, rows: list[dict]):
    cols = ["id", "symbol", "side", "lots", "decision_utc", "ref_price", "sl", "tp", "why", "fill_utc",
            "fill_price", "slippage", "expected_half_spread", "slippage_vs_expected", "rejected_reason",
            "exit_utc", "exit_price", "exit_reason", "result", "net_usd", "r_price", "r_net"]
    with open(path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(cols)
        for r in rows:
            w.writerow([r.get(c, "") for c in cols])


def build(home: Path = HOME) -> dict:
    state = home / "state"
    rows = read_ledger(state / "ledger.jsonl")
    fills = [r for r in rows if r["type"] in FILL_TYPES]

    with open(state / "fills.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["utc", "bar", "type", "id", "side", "lots", "price", "sl", "tp", "result", "net_usd", "r_multiple", "detail"])
        for r in fills:
            w.writerow([r.get("utc"), r.get("bar"), r["type"], r.get("id", ""), r.get("side", ""), r.get("lots", ""),
                        r.get("entry", r.get("exit", "")), r.get("sl", r.get("new_sl", "")), r.get("tp", ""),
                        r.get("result", ""), r.get("net_usd", ""), r.get("r_multiple", ""), describe(r)])

    entry_rows = entries(rows)
    write_entries_csv(state / "entries.csv", entry_rows)

    account = json.loads((state / "account.json").read_text()) if (state / "account.json").exists() else {}
    trs = [r for r in rows if r["type"] == "trade_closed"]
    wins = sum(1 for r in trs if r["result"] == "win")
    losses = sum(1 for r in trs if r["result"] == "loss")
    tbl = "".join(
        f"<tr><td>{html.escape(str(r.get('utc', '')))}</td><td>{html.escape(r['type'])}</td>"
        f"<td>{html.escape(str(r.get('id', '')))}</td><td>{html.escape(describe(r))}</td></tr>"
        for r in fills[-300:][::-1])
    open_pos = "".join(
        f"<li>#{p['id']} {p['side']} {p['lots']} @ {p['entry']} sl {p['sl']} tp {p['tp']} (opened {p['opened_utc']})</li>"
        for p in account.get("positions", [])) or "<li>none</li>"
    pend = "".join(f"<li>{html.escape(o['kind'])} #{o['id']} {html.escape(str(o.get('side', '')))}</li>"
                   for o in account.get("pending", [])) or "<li>none</li>"
    eq = account.get("equity", R.START_BALANCE)

    def flag(r):
        d = r.get("slippage_vs_expected")
        return d is not None and d > 5 * (r.get("expected_half_spread") or 0.0001)

    entry_tbl = "".join(
        f"<tr class=\"{'warn' if flag(r) else ''}\"><td>{html.escape(str(r['id']))}</td>"
        f"<td>{html.escape(str(r['symbol']))}</td><td>{html.escape(str(r['side']))}</td>"
        f"<td>{html.escape(str(r['decision_utc']))}</td><td>{r['ref_price']}</td>"
        f"<td>{r['sl']}</td><td>{r['tp']}</td>"
        f"<td>{html.escape(str(r['fill_utc'] or ''))}</td><td>{r['fill_price'] if r['fill_price'] is not None else ''}</td>"
        f"<td>{r['slippage'] if r['slippage'] is not None else ''}</td>"
        f"<td>{html.escape(str(r['exit_utc'] or ''))}</td><td>{r['exit_price'] if r['exit_price'] is not None else ''}</td>"
        f"<td>{html.escape(str(r['result'] or r.get('rejected_reason') or ''))}</td>"
        f"<td>{r['r_price'] if r['r_price'] is not None else ''}</td></tr>"
        for r in entry_rows[::-1][:200])
    page = f"""<!doctype html><html><head><meta charset="utf-8"><title>FTMO field — fills</title>
<style>
:root {{ --fg:#1d1d1f; --bg:#fff; --mut:#666; --line:#e4e4e4; }}
@media (prefers-color-scheme: dark) {{ :root:not([data-theme="light"]) {{ --fg:#eee; --bg:#111; --mut:#999; --line:#333; }} }}
body {{ font: 14px/1.4 system-ui, sans-serif; color:var(--fg); background:var(--bg); margin:16px; }}
table {{ border-collapse: collapse; width:100%; }} td,th {{ border-bottom:1px solid var(--line); padding:4px 6px; text-align:left; vertical-align:top; }}
.kpi span {{ display:inline-block; margin-right:18px; }} .mut {{ color:var(--mut); }} tr.warn {{ background:rgba(220,120,0,0.12); }}
</style></head><body>
<h2>FTMO field — paper fills</h2>
<p class="mut">paper only, demo; regenerated {html.escape(str(account.get('utc', 'not started')))} · bar {account.get('bar_index', 0)}/{account.get('bars_total', 0)}</p>
<div class="kpi"><span>equity <b>{eq:.2f}</b></span><span>day pnl <b>{eq - account.get('day_start_equity', R.START_BALANCE):.2f}</b></span>
<span>closed trades <b>{len(trs)}</b> (win {wins} / loss {losses})</span><span>traded days <b>{account.get('traded_days', 0)}</b></span>
<span>breached <b>{account.get('breached') or 'no'}</b></span></div>
<h3>equity</h3>{svg_curve(equity_points(rows))}
<h3>open positions</h3><ul>{open_pos}</ul>
<h3>pending</h3><ul>{pend}</ul>
<h3>entries — decision vs fill vs close (replay check; orange = slippage over 5x the expected half-spread; also in state/entries.csv)</h3>
<table><tr><th>id</th><th>sym</th><th>side</th><th>decided</th><th>ref</th><th>sl</th><th>tp</th>
<th>filled</th><th>fill px</th><th>slip</th><th>exit</th><th>exit px</th><th>result</th><th>R</th></tr>{entry_tbl}</table>
<h3>timeline (newest first, last 300)</h3>
<table><tr><th>utc</th><th>type</th><th>id</th><th>detail</th></tr>{tbl}</table>
</body></html>"""
    (state / "fills.html").write_text(page)
    return {"fills": len(fills), "closed": len(trs), "entries": len(entry_rows), "html": str(state / "fills.html"),
            "csv": str(state / "fills.csv"), "entries_csv": str(state / "entries.csv")}


if __name__ == "__main__":
    print(json.dumps(build(), indent=1))
